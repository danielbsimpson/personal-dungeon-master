"""
Phase I — MemoRAG for long campaigns.

Generates and stores compact memory *clues* from each session's episodes.
At query time, the most relevant clues are retrieved and prepended to the
retrieval query so that Graphiti's edge search benefits from richer context.

This mirrors the "Memory Clue" concept from the MemoRAG paper (Qian et al.,
2024): instead of storing raw episode text, we distil each session into a
handful of high-signal facts that guide downstream retrieval.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Awaitable, Callable

import numpy as np

log = logging.getLogger(__name__)

_CLUE_PROMPT = """\
You are a record-keeper for a tabletop RPG campaign.

Recent DM narrations:
{episodes}

Extract {n} concise memory clues — short, specific facts about events, \
characters, items, or locations that would be useful for future reference.

Format: one clue per line, no numbering, no bullets. Be specific and factual."""


def _cosine(a: list[float], b: list[float]) -> float:
    va = np.array(a, dtype=np.float32)
    vb = np.array(b, dtype=np.float32)
    na, nb = np.linalg.norm(va), np.linalg.norm(vb)
    if na == 0.0 or nb == 0.0:
        return 0.0
    return float(np.dot(va, vb) / (na * nb))


@dataclass
class MemoryClue:
    """A single distilled fact from a past session."""

    clue_id: int
    text: str
    session: int            # session number this clue was extracted from
    embedding: list[float]


class MemoRAGStore:
    """
    Stores and retrieves compact memory clues distilled from session episodes.

    Clues are generated by the LLM at the end of each session and persist
    across sessions via JSON serialisation.  At query time, the top-k most
    relevant clues are injected into the retrieval query to boost recall.
    """

    def __init__(self, clues: list[MemoryClue] | None = None) -> None:
        self.clues: list[MemoryClue] = clues or []

    # ------------------------------------------------------------------
    # Population
    # ------------------------------------------------------------------

    async def add_clues(
        self,
        session_episodes: list[str],
        session_number: int,
        embed_fn: Callable[[list[str]], Awaitable[list[list[float]]]],
        summarise_fn: Callable[[str], Awaitable[str]],
        clues_per_session: int = 5,
    ) -> None:
        """
        Generate *clues_per_session* clues from *session_episodes* and store them.

        Parameters
        ----------
        session_episodes:
            The DM narrations from the session just ended.
        session_number:
            A monotonically increasing session counter.
        embed_fn:
            Async callable: ``list[str] -> list[list[float]]``.
        summarise_fn:
            Async callable wrapping the LLM (prompt → response text).
        clues_per_session:
            How many clues to extract from the session.
        """
        if not session_episodes:
            return

        combined = "\n\n".join(session_episodes)
        prompt = _CLUE_PROMPT.format(episodes=combined, n=clues_per_session)

        try:
            raw_clues = await summarise_fn(prompt)
        except Exception as exc:  # noqa: BLE001
            log.warning("MemoRAG clue generation failed (%s); skipping.", exc)
            return

        clue_texts = [
            line.strip()
            for line in raw_clues.splitlines()
            if line.strip()
        ][:clues_per_session]

        if not clue_texts:
            return

        try:
            embeddings = await embed_fn(clue_texts)
        except Exception as exc:  # noqa: BLE001
            log.warning("MemoRAG clue embedding failed (%s); skipping.", exc)
            return

        start_id = len(self.clues)
        for i, (text, emb) in enumerate(zip(clue_texts, embeddings)):
            self.clues.append(
                MemoryClue(
                    clue_id=start_id + i,
                    text=text,
                    session=session_number,
                    embedding=emb,
                )
            )

        log.info(
            "MemoRAG: added %d clues for session %d (total %d).",
            len(clue_texts),
            session_number,
            len(self.clues),
        )

    # ------------------------------------------------------------------
    # Retrieval
    # ------------------------------------------------------------------

    def retrieve_clues(
        self, query_embedding: list[float], top_k: int = 3
    ) -> list[MemoryClue]:
        """Return the *top_k* clues most similar to *query_embedding*."""
        if not self.clues:
            return []
        scored = [
            (_cosine(query_embedding, c.embedding), c) for c in self.clues
        ]
        scored.sort(key=lambda x: x[0], reverse=True)
        return [c for _, c in scored[:top_k]]

    def augment_query(
        self,
        original_query: str,
        query_embedding: list[float],
        top_k: int = 3,
    ) -> str:
        """
        Prepend the most relevant clues to *original_query*.

        Returns *original_query* unchanged when no relevant clues are found.
        """
        clues = self.retrieve_clues(query_embedding, top_k=top_k)
        if not clues:
            return original_query
        clue_text = " ".join(c.text for c in clues)
        return f"{original_query} Context: {clue_text}"

    # ------------------------------------------------------------------
    # Persistence
    # ------------------------------------------------------------------

    def save(self, path: Path) -> None:
        """Serialise the clue store to a JSON file at *path*."""
        path.parent.mkdir(parents=True, exist_ok=True)
        data = {
            "clues": [
                {
                    "clue_id": c.clue_id,
                    "text": c.text,
                    "session": c.session,
                    "embedding": c.embedding,
                }
                for c in self.clues
            ]
        }
        path.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
        log.info("MemoRAG: saved %d clues to %s.", len(self.clues), path)

    @classmethod
    def load(cls, path: Path) -> "MemoRAGStore":
        """Load a previously saved clue store from *path*."""
        raw = json.loads(path.read_text(encoding="utf-8"))
        clues = [
            MemoryClue(
                clue_id=c["clue_id"],
                text=c["text"],
                session=c["session"],
                embedding=c["embedding"],
            )
            for c in raw["clues"]
        ]
        store = cls(clues=clues)
        log.info("MemoRAG: loaded %d clues from %s.", len(clues), path)
        return store
